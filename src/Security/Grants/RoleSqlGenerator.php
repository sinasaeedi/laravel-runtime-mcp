<?php

declare(strict_types=1);

namespace SinaSaeedi\RuntimeMcp\Security\Grants;

use InvalidArgumentException;
use SinaSaeedi\RuntimeMcp\Security\UnsupportedDriver;

/**
 * Spec 5.1, 7.1: the copy-paste SQL for the read-only role. The grants are the column mask and the
 * table denylist (rule 13): no grant on a denied table, a column-level grant on a table with a masked
 * column. Never a default-privilege grant (rule 7). It prints SQL; it never runs it.
 */
final class RoleSqlGenerator
{
    public const DEFAULT_ROLE = 'runtime_mcp_ro';

    public const DEFAULT_HOST = '%';

    public const ROLE_PATTERN = '/^[A-Za-z_][A-Za-z0-9_]{0,31}$/D';

    public const HOST_PATTERN = '/^[A-Za-z0-9.%_:-]{1,255}$/D';

    private const CLOSING = '-- New tables get NO grant automatically. Add a GRANT when you add a table.';

    public function __construct(
        private readonly ColumnMask $mask,
        private readonly DeniedTables $denied,
        private readonly string $appName,      // config('app.name')
        private readonly string $environment,  // Environment::name()
    ) {}

    public function forPostgres(SchemaSnapshot $snapshot, string $role = self::DEFAULT_ROLE): string
    {
        self::assertRole($role);

        $grantee = self::quotePostgres($role);
        $plan = $this->plan($snapshot, self::quotePostgres(...));

        $lines = [
            "-- Runtime MCP read-only role for {$this->header()}.",
            '-- Generated by sinasaeedi/laravel-runtime-mcp. Review it, set a strong password, and run it as the',
            '-- database owner or a superuser. Re-run `php artisan runtime-mcp:doctor` afterwards.',
            "CREATE ROLE {$grantee} LOGIN PASSWORD 'CHANGE_ME'",
            '    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;',
            'GRANT CONNECT ON DATABASE '.self::quotePostgres($snapshot->database)." TO {$grantee};",
        ];

        foreach ($plan['schemas'] as $schema) {
            $lines[] = 'GRANT USAGE ON SCHEMA '.self::quotePostgres($schema)." TO {$grantee};";
        }

        foreach ($plan['grants'] as [$table, $columns]) {
            $lines[] = $columns === null
                ? "GRANT SELECT ON TABLE {$table} TO {$grantee};"
                : 'GRANT SELECT ('.implode(', ', $columns).") ON TABLE {$table} TO {$grantee};";
        }

        return self::finish($lines, $plan);
    }

    public function forMySql(SchemaSnapshot $snapshot, string $role = self::DEFAULT_ROLE, string $host = self::DEFAULT_HOST): string
    {
        self::assertRole($role);

        if (preg_match(self::HOST_PATTERN, $host) !== 1) {
            throw new InvalidArgumentException('The MySQL host must match /^[A-Za-z0-9.%_:-]{1,255}$/, for example % or 10.0.%.');
        }

        // The patterns allow no quote, so the literals need no escaping.
        $grantee = "'{$role}'@'{$host}'";
        $plan = $this->plan($snapshot, self::quoteMySql(...));

        $lines = [
            "-- Runtime MCP read-only user for {$this->header()}.",
            '-- Generated by sinasaeedi/laravel-runtime-mcp. Review it, set a strong password, and run it as a user',
            '-- that can create users and grant privileges. Re-run `php artisan runtime-mcp:doctor` afterwards.',
            '-- MySQL and MariaDB have no CONNECT or schema USAGE grant: CREATE USER gives USAGE, which is no privilege.',
        ];

        if ($host === '%') {
            $lines[] = "-- Host '%' accepts a connection from any host. Narrow it if you can (runtime-mcp:install --host).";
        }

        $lines[] = "CREATE USER {$grantee} IDENTIFIED BY 'CHANGE_ME';";

        foreach ($plan['grants'] as [$table, $columns]) {
            $lines[] = $columns === null
                ? "GRANT SELECT ON {$table} TO {$grantee};"
                : 'GRANT SELECT ('.implode(', ', $columns).") ON {$table} TO {$grantee};";
        }

        return self::finish($lines, $plan);
    }

    /** pgsql → forPostgres ($host is ignored); mysql, mariadb → forMySql; anything else → UnsupportedDriver. */
    public function forDriver(string $driver, SchemaSnapshot $snapshot, string $role = self::DEFAULT_ROLE, string $host = self::DEFAULT_HOST): string
    {
        return match ($driver) {
            'pgsql' => $this->forPostgres($snapshot, $role),
            'mysql', 'mariadb' => $this->forMySql($snapshot, $role, $host),
            default => throw new UnsupportedDriver($driver),
        };
    }

    /** "…" with every " doubled. 01-13 reuses it for its fix lines. */
    public static function quotePostgres(string $identifier): string
    {
        return '"'.str_replace('"', '""', $identifier).'"';
    }

    /** `…` with every ` doubled. 01-13 reuses it for its fix lines. */
    public static function quoteMySql(string $identifier): string
    {
        return '`'.str_replace('`', '``', $identifier).'`';
    }

    /**
     * The decision per table, in snapshot order. Names come back quoted and fully qualified.
     *
     * @param  callable(string): string  $quote
     * @return array{
     *     schemas: list<string>,
     *     grants: list<array{0: string, 1: list<string>|null}>,
     *     denied: list<string>,
     *     allMasked: list<string>,
     *     masked: list<string>,
     * }
     */
    private function plan(SchemaSnapshot $snapshot, callable $quote): array
    {
        $plan = ['grants' => [], 'denied' => [], 'allMasked' => [], 'masked' => []];
        $schemas = [];

        foreach ($snapshot->tables as $table) {
            $qualified = $quote($table->schema).'.'.$quote($table->name);
            // The comment lists get the name on one line: a line break would end the comment and run
            // the rest of the name as SQL. The GRANT keeps the exact name, which the quotes hold.
            $listed = self::oneLine($qualified);

            if ($this->denied->contains($table->schema, $table->name, $snapshot->prefix)) {
                $plan['denied'][] = $listed;

                continue;
            }

            $readable = [];
            $masked = [];

            foreach ($table->columns as $column) {
                if ($this->mask->matches($column)) {
                    $masked[] = $listed.'.'.self::oneLine($quote($column));
                } else {
                    $readable[] = $quote($column);
                }
            }

            // A grant on zero columns is not valid SQL, and the table is effectively denied.
            if ($readable === []) {
                $plan['allMasked'][] = $listed;

                continue;
            }

            $plan['grants'][] = [$qualified, $masked === [] ? null : $readable];
            $plan['masked'] = [...$plan['masked'], ...$masked];
            // USAGE only on a schema with at least one grant.
            $schemas[$table->schema] = $table->schema;
        }

        $schemas = array_values($schemas);
        usort($schemas, strcmp(...));

        return ['schemas' => $schemas, ...$plan];
    }

    /**
     * @param  list<string>  $lines
     * @param  array{denied: list<string>, allMasked: list<string>, masked: list<string>}  $plan
     */
    private static function finish(array $lines, array $plan): string
    {
        $comments = [
            '-- No grant (denied_tables): ' => $plan['denied'],
            '-- No grant (every column masked): ' => $plan['allMasked'],
            '-- Masked columns (not granted): ' => $plan['masked'],
        ];

        foreach ($comments as $label => $names) {
            if ($names !== []) {
                $lines[] = $label.implode(', ', $names);
            }
        }

        $lines[] = self::CLOSING;

        return implode("\n", $lines)."\n";
    }

    /** The app name and the environment, on one comment line: a line break would start a line the operator runs. */
    private function header(): string
    {
        $app = self::oneLine($this->appName);

        return ($app === '' ? 'this app' : $app).' ('.self::oneLine($this->environment).')';
    }

    /** Every control character becomes a space, so the text cannot leave its comment line. */
    private static function oneLine(string $text): string
    {
        return preg_replace('/[\x00-\x1F\x7F]/', ' ', $text) ?? '';
    }

    private static function assertRole(string $role): void
    {
        if (preg_match(self::ROLE_PATTERN, $role) !== 1) {
            throw new InvalidArgumentException(
                'The role name must match /^[A-Za-z_][A-Za-z0-9_]{0,31}$/ (letters, digits and _, at most 32 characters).'
            );
        }
    }
}
